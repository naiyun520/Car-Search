import assert from 'node:assert/strict'
import { createHmac } from 'node:crypto'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const route = read('car-admin/route/app.php')
const schema = read('car-admin/database/schema.sql')
const upgrade = read('car-admin/app/command/UpgradeCommand.php')
const checkout = read('car-admin/app/service/CheckoutService.php')
const checkoutController = read('car-admin/app/controller/CheckoutController.php')
const apiRequest = read('car-admin/app/service/ApiRequestService.php')
const payment = read('car-admin/app/service/PaymentService.php')
const clientPayment = read('car-miniapp/src/utils/payment.js')
const wechat = read('car-admin/app/service/WechatService.php')
const request = read('car-miniapp/src/utils/request.js')
const queryPage = read('car-miniapp/src/pages/query/query.vue')
const ordersPage = read('car-miniapp/src/pages/orders/orders.vue')
const adminApp = read('car-admin/public/admin/app.js')
const queryRunner = read('car-admin/app/service/QueryRunnerService.php')
