const builtQuery = read('car-miniapp/dist/build/mp-weixin/pages/query/query.js')
const protocol = read('car-miniapp/src/utils/protocol.js')

for (const endpoint of ['checkout/create','checkout/status','checkout/payment','checkout/confirm','checkout/query','checkout/recoverable']) {
  assert.match(route, new RegExp(`['\"]${endpoint.replace('/', '\\/')}['\"]`), `route missing: ${endpoint}`)
}
assert.ok(!route.includes("Route::post('checkout','"), 'ambiguous legacy checkout route must not exist')
for (const field of ['request_key','query_attempts','query_last_error','last_checked_at']) {
  assert.ok(schema.includes(`\`${field}\``), `schema missing ${field}`)
  assert.ok(upgrade.includes(`'${field}'`), `upgrade missing ${field}`)
}
assert.ok(schema.includes('uk_user_request'), 'idempotency unique index missing')
assert.ok(checkout.includes("where('code', $serviceCode)->where('status', 1)"), 'checkout must resolve active service by code')
assert.ok(checkoutController.includes("$payload['service_code'] ?? $this->request->get('service_code', '')"), 'server JSON/query service-code fallback missing')
assert.ok(checkoutController.includes("$this->request->param('order_no', '')"), 'server order-number fallback missing')
assert.ok(apiRequest.includes('requiredTransportValue'), 'dual-channel transport validation missing')
assert.ok(apiRequest.includes('业务标识不一致'), 'dual-channel mismatch guard missing')
assert.ok(checkout.includes('service_snapshot_cipher'), 'checkout must freeze provider configuration')
assert.ok(payment.includes("[2,3,4]"), 'only paid WeChat states may fulfil')
assert.ok(payment.includes('payment_review'), 'payment mismatch review state missing')
assert.ok(payment.includes('rememberWechatCheck'), 'WeChat pending-state observability missing')
assert.ok(!clientPayment.includes('getSystemInfoSync'), 'deprecated getSystemInfoSync remains in payment flow')
assert.ok(clientPayment.includes('paymentUncertain'), 'payment failures are not classified')
assert.ok(clientPayment.includes("systemPlatform === 'devtools'"), 'developer simulator detection missing')
assert.ok(wechat.includes("'left_fee'=>$leftFee"), 'refund left_fee missing')
assert.ok(request.includes("JSON.stringify(options.data || {})"), 'JSON transport not explicit')
assert.ok(request.includes('data.service_code = serviceCode'), 'service code must be duplicated in JSON body')
assert.ok(request.includes('data.order_no = orderNo'), 'order number must be duplicated in JSON body')
assert.ok(request.includes('data.request_key = idempotencyKey'), 'idempotency key must be duplicated in JSON body')
assert.ok(request.includes('order_no=${encodeURIComponent(orderNo)}'), 'GET order number query fallback missing')
assert.ok(queryPage.includes("saveFlow({ request_key:requestKey"), 'idempotency key must be persisted before request')
assert.ok(queryPage.includes('data:{ service_code:serviceCode, request_key:requestKey'), 'checkout page must carry identifiers explicitly')
assert.ok(queryPage.includes('/checkout/create?service_code='), 'unambiguous checkout create URL missing')
assert.ok(queryPage.includes('!isTransientRequestError(error)'), 'permanent confirm errors must not be polled')
assert.ok(protocol.includes("20260815.1") && checkout.includes("20260815.1"), 'client/server protocol versions differ')
assert.ok(!queryPage.includes('confirmContinuePayment'), 'unpaid orders must not be restored or advertised')
assert.ok(!queryPage.includes("order.status === 'paid' || order.status === 'query_failed'"), 'failed queries must not be submitted again by the client')
assert.ok(!ordersPage.includes("query_failed:'重试'"), 'history must not offer self-service provider retries')
assert.ok(ordersPage.includes("query_failed:'联系客服'"), 'failed paid orders must direct users to support')
assert.ok(queryRunner.includes('retryFromAdmin') && !queryRunner.includes('RETRY_COOLDOWN_SECONDS'), 'provider retries must be administrator-only')
assert.ok(queryRunner.includes('refreshServiceSnapshotForAdmin') && queryRunner.includes('inputKeys'), 'administrator retry must safely refresh corrected provider configuration')
assert.ok(route.includes("Route::get('order-detail/:orderNo'"), 'unambiguous admin order-detail route missing')
assert.ok(!route.includes("Route::get('orders/:orderNo'"), 'ambiguous order detail route must not exist')
assert.ok(!route.includes("Route::get('feedback/:id'"), 'ambiguous feedback detail route must not exist')
assert.ok(adminApp.includes('/order-detail/${encodeURIComponent'), 'admin must use unambiguous detail endpoint')
assert.ok(adminApp.includes('订单详情响应格式异常'), 'admin detail response contract guard missing')
assert.ok(route.includes("Route::post('service-test/:id'"), 'service test route missing')
assert.ok(serviceAdmin.includes('InputValidator::validate') && serviceAdmin.includes('ProviderService::query'), 'service test must reuse paid-order validation and provider path')
assert.ok(serviceAdmin.includes("'service.test'"), 'service tests must be audited')
assert.ok(serviceUi.includes('test-service') && serviceUi.includes('/service-test/'), 'service test UI missing')
assert.ok(serviceUi.includes('可能产生接口费用'), 'billable test warning missing')
assert.ok(!builtQuery.includes('services/${'), 'production miniapp still contains dynamic service checkout route')
assert.ok(!builtQuery.includes('功能定位失败'), 'obsolete diagnosis leaked into production build')

// Official formula: hex(HMAC-SHA256(key, uri + '&' + exact JSON string)).
const key = 'contract-test-app-key'
const body = JSON.stringify({ openid:'o-test', env:1, order_id:'260814123456000520ABCDEF12' })
const expected = createHmac('sha256', key).update(`/xpay/query_order&${body}`).digest('hex')
assert.equal(expected.length, 64)
assert.equal(expected, createHmac('sha256', key).update(`/xpay/query_order&${body}`).digest('hex'))

